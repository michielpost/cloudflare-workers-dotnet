using System.Threading.Tasks;
using Shared;
using Workers;

namespace WorkersDotNet
{
    /// <summary>
    /// Sample: the Workers Cache API (<c>caches.default</c>).
    /// </summary>
    /// <remarks>
    /// The first GET for a cache key produces a fresh payload and stores the
    /// response in the cache. Every later GET for the same key is answered from
    /// the cache, so <c>EntryId</c> and <c>GeneratedAtUtc</c> stay frozen while
    /// the <c>x-cache</c> response header flips from "miss" to "hit".
    /// A POST deletes the entry again, which makes the next GET a miss.
    /// The full request URL (including <c>?key=</c> used by the UI) is the cache
    /// key, so different keys are cached independently.
    /// </remarks>
    public sealed class CacheEndpoint
    {
        public async Task<Response> HandleAsync(Request request, ExecutionContext context)
        {
            var cacheKey = request.Url;

            if (request.Method == "POST")
                return await PurgeAsync(cacheKey);

            var cached = await CacheStorage.Default.MatchAsync(cacheKey);
            if (cached is not null)
            {
                // A response from the Cache API has immutable headers, so the
                // hit markers cannot be set on it directly. Copy the headers into
                // a new response instead.
                var hitHeaders = new Headers(cached.Headers);
                hitHeaders.Set("x-cache", "hit");
                hitHeaders.Set("x-cache-key", cacheKey);
                hitHeaders.Set("x-cache-note", "Served from caches.default on the edge");
                hitHeaders.Set("cache-control", "no-store");
                return Results.Copy(cached, hitHeaders);
            }

            var payload = new CachePayload(
                cacheKey,
                Crypto.RandomUuid(),
                Clock.NowIso(),
                "Generated by the worker, then stored in the Cache API.");

            // The stored copy needs a cacheable "cache-control": the Cache API
            // quietly refuses to store a response marked "no-store". It is built
            // from its own response instance, because a Response body can only be
            // handed to the Response constructor once.
            var stored = Response.Json(payload, 200);
            stored.Headers.Set("x-cache", "miss");
            stored.Headers.Set("x-cache-key", cacheKey);
            stored.Headers.Set("cache-control", "max-age=300");

            // Writing to the cache must finish even though the response is
            // returned right away, so hand the task to the runtime.
            context.WaitUntil(CacheStorage.Default.PutAsync(cacheKey, stored));

            // The client response uses "no-store" so the browser never serves its
            // own copy; every click then really reaches the worker and the
            // hit/miss flips stay visible.
            var response = Response.Json(payload, 200);
            response.Headers.Set("x-cache", "miss");
            response.Headers.Set("x-cache-key", cacheKey);
            response.Headers.Set("x-cache-note", "Freshly generated and written to caches.default");
            response.Headers.Set("cache-control", "no-store");
            return response;
        }

        static async Task<Response> PurgeAsync(string cacheKey)
        {
            var deleted = await CacheStorage.Default.DeleteAsync(cacheKey);

            var message = deleted
                ? "Cache entry deleted. The next GET is a cache miss."
                : "There was no cache entry for this key, so the next GET is already a miss.";

            var response = Response.Json(new Shared.CachePurgeResult(deleted, cacheKey, message), 200);
            response.Headers.Set("x-cache", "purged");
            response.Headers.Set("x-cache-key", cacheKey);
            response.Headers.Set("cache-control", "no-store");
            return response;
        }
    }
}
